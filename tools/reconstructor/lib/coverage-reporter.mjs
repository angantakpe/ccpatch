/**
 * Generate a COVERAGE.md report summarizing reconstruction results.
 */

import path from 'node:path';
import { writeText, log } from './utils.mjs';

/**
 * Generate the coverage report.
 *
 * @param {import('./reconstructor.mjs').ReconstructionResult} result
 * @param {import('./aligner.mjs').AlignmentResult} alignment
 * @param {string} outputDir
 * @param {Object} meta - { baseVersion, targetVersion, baseBundle, targetBundle }
 */
export function generateCoverageReport(result, alignment, outputDir, meta) {
  const skipped = result.skipped || 0;
  const totalAll = result.exactCopied + result.modified + result.newModules + result.deleted + skipped;
  const totalOutput = result.exactCopied + result.modified + result.newModules;

  const pct = (n) => totalOutput > 0 ? ((n / totalOutput) * 100).toFixed(1) : '0.0';

  // Classify modified files into "reconstructed with diffs" vs "annotation only"
  const modifiedManifest = result.manifest.filter(m => m.type === 'modified');
  const reconstructedWithDiffs = modifiedManifest.filter(m => m.hasDiffs).length;
  const annotationOnly = result.modified - reconstructedWithDiffs;

  const lines = [
    '# Reconstruction Coverage Report',
    '',
    `> Generated by bundle-reconstructor (regle de trois)`,
    `> Date: ${new Date().toISOString().slice(0, 10)}`,
    '',
    '## Metadata',
    '',
    `| Field | Value |`,
    `|-------|-------|`,
    `| Base version | ${meta.baseVersion || 'unknown'} |`,
    `| Target version | ${meta.targetVersion || 'unknown'} |`,
    `| Base bundle | ${meta.baseBundle || 'N/A'} |`,
    `| Target bundle | ${meta.targetBundle || 'N/A'} |`,
    '',
    '## File Inventory',
    '',
    `| Category | Count | % of Output |`,
    `|----------|------:|------------:|`,
    `| High-confidence match (exact copy) | ${result.exactCopied} | ${pct(result.exactCopied)}% |`,
    `| Reconstructed with diffs | ${reconstructedWithDiffs} | ${pct(reconstructedWithDiffs)}% |`,
    `| Annotation only (diffs could not be mapped) | ${annotationOnly} | ${pct(annotationOnly)}% |`,
    `| Raw minified JS (new modules) | ${result.newModules} | ${pct(result.newModules)}% |`,
    `| Skipped (no base content found) | ${skipped} | — |`,
    `| Deleted (removed in target) | ${result.deleted} | — |`,
    `| **Files in output** | **${totalOutput}** | **100%** |`,
    `| **Total files processed** | **${totalAll}** | |`,
    '',
    '## Reconstruction Fidelity',
    '',
    'What the output actually contains:',
    '',
    `- **High-confidence match**: ${result.exactCopied} files (${pct(result.exactCopied)}%) — all modules matched with ≥98% string sequence similarity (base source copied)`,
    `- **Best-effort reconstruction**: ${reconstructedWithDiffs} files (${pct(reconstructedWithDiffs)}%) — base source with diffs applied from minified code analysis`,
    `- **Unverified base copy**: ${annotationOnly} files (${pct(annotationOnly)}%) — base source copied with change annotations only, diffs could not be mapped`,
    `- **Not TypeScript**: ${result.newModules} files (${pct(result.newModules)}%) — raw minified JavaScript, no base source available`,
    `- **Missing**: ${skipped} files (${pct(skipped)}%) — referenced in source map but no content could be retrieved`,
    `- **Stale**: ${result.deleted} files (${pct(result.deleted)}%) — base source likely removed in target version`,
    '',
    '## Quality Assessment',
    '',
    ...(annotationOnly > reconstructedWithDiffs
      ? [
          `> **⚠ WARNING**: ${annotationOnly} of ${result.modified} modified files have NO actual diffs applied.`,
          '> These files are verbatim copies of the base version with annotation headers only.',
          '> The reconstruction tool detected changes but could not map them back to source.',
          '> These files should be treated as **unverified** — they may differ from the target version.',
          '',
        ]
      : [
          `✓ ${reconstructedWithDiffs} of ${result.modified} modified files have real diffs applied.`,
          '',
        ]),
    '## Alignment Statistics',
    '',
    `| Metric | Value |`,
    `|--------|------:|`,
    `| Base modules | ${alignment.stats.totalBase} |`,
    `| Target modules | ${alignment.stats.totalTarget} |`,
    `| Matched pairs | ${alignment.stats.matched} |`,
    `| Anchor strings used | ${alignment.stats.anchorCount} |`,
    `| Exact matches | ${alignment.stats.exact} |`,
    `| Modified matches | ${alignment.stats.modified} |`,
    `| Unmatched base (deleted) | ${alignment.stats.deleted} |`,
    `| Unmatched target (new) | ${alignment.stats.new} |`,
    '',
  ];

  // Modified files detail
  const modifiedFiles = result.manifest.filter(m => m.type === 'modified');
  if (modifiedFiles.length > 0) {
    lines.push('## Modified Files');
    lines.push('');
    lines.push('| File | Confidence | Modules | Code Diffs | Annotations | Unmapped |');
    lines.push('|------|-----------|---------|-----------|-------------|----------|');
    for (const f of modifiedFiles.sort((a, b) => a.confidence - b.confidence)) {
      const diffs = f.realDiffCount ?? (f.hasDiffs ? '?' : '0');
      const annots = f.annotationCount ?? '?';
      const unmapped = f.unmappedCount ?? '?';
      lines.push(`| \`${f.path}\` | ${(f.confidence * 100).toFixed(0)}% | ${f.moduleCount || '?'} | ${diffs} | ${annots} | ${unmapped} |`);
    }
    lines.push('');
  }

  // New modules detail
  const newFiles = result.manifest.filter(m => m.type === 'new');
  if (newFiles.length > 0) {
    lines.push('## New Modules (Manual Review Needed)');
    lines.push('');
    for (const f of newFiles) {
      lines.push(`- \`${f.path}\``);
    }
    lines.push('');
  }

  // Skipped files detail
  const skippedFiles = result.manifest.filter(m => m.type === 'skipped');
  if (skippedFiles.length > 0) {
    lines.push('## Skipped Files (No Base Content)');
    lines.push('');
    lines.push('These files were referenced in the source map but no base content could be found.');
    lines.push('They are completely absent from the output.');
    lines.push('');
    for (const f of skippedFiles) {
      lines.push(`- \`${f.path}\``);
    }
    lines.push('');
  }

  // Deleted files detail
  const deletedFiles = result.manifest.filter(m => m.type === 'deleted');
  if (deletedFiles.length > 0) {
    lines.push('## Potentially Deleted Files');
    lines.push('');
    for (const f of deletedFiles) {
      lines.push(`- \`${f.path}\``);
    }
    lines.push('');
  }

  lines.push('---');
  lines.push('*Generated by [bundle-reconstructor](src/cli/bundle-reconstructor/) — règle de trois*');

  const reportPath = path.join(outputDir, 'COVERAGE.md');
  writeText(reportPath, lines.join('\n'));
  log('report', `Coverage report written to ${reportPath}`);

  // Also write machine-readable manifest
  const manifestPath = path.join(outputDir, 'manifest.json');
  writeText(manifestPath, JSON.stringify({
    meta,
    summary: {
      exactCopied: result.exactCopied,
      modified: result.modified,
      reconstructedWithDiffs,
      annotationOnly,
      newModules: result.newModules,
      deleted: result.deleted,
      skipped,
      totalAll,
      totalOutput,
    },
    alignmentStats: alignment.stats,
    files: result.manifest,
  }, null, 2));
  log('report', `Manifest written to ${manifestPath}`);
}
